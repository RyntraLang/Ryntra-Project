#include "Init.h"
#include "Manifest.h"
#include "Pipeline.h"

#include "ArgParsing/ArgParsing.h"
#include "ErrorHandler/ErrorHandler.h"
#include "ErrorHandler/RuntimeError.h"
#include "VM/VirtualMachine.h"

#include <filesystem>
#include <iostream>
#include <print>
#include <string>

namespace {
    void printUsage(const char *prog) {
        std::print(std::cerr, "Usage: {} <command> [args] [options]\n\n", prog);
        std::print(std::cerr, "Commands:\n");
        std::print(std::cerr, "  build <Target>   Compile the target and run it in-process.\n");
        std::print(std::cerr, "  run <Target>     Alias of build.\n");
        std::print(std::cerr, "  check <Target>   Compile only (diagnostics, no run).\n");
        std::print(std::cerr, "  init <path>      Scaffold a new project (Riko.toml + src/main.rynt).\n\n");
        std::print(std::cerr, "Options:\n");
        std::print(std::cerr, "  --manifest-path <file>  Path to Riko.toml (default: ./Riko.toml)\n");
        std::print(std::cerr, "  --target <Name>         Target name (alternative to the positional argument)\n");
        std::print(std::cerr, "  --emit-ir               Print the generated IR\n");
        std::print(std::cerr, "  --emit-bytecode         Print the generated bytecode disassembly\n");
        std::print(std::cerr, "  -v, --verbose           Verbose output\n");
        std::print(std::cerr, "  -h, --help              Show this help\n");
    }
} // namespace

int main(int argc, char **argv) {
    using namespace Ryntra::Utility;
    using namespace Ryntra::BuildSystem;

    ArgParser parser(argc, argv);
    auto manifestPathOpt = parser.option<std::string>("--manifest-path").help("Path to Riko.toml");
    auto targetOpt = parser.option<std::string>("--target").help("Target name");
    auto emitIR = parser.flag("--emit-ir").help("Print the generated IR");
    auto emitBytecode = parser.flag("--emit-bytecode").help("Print the generated bytecode");
    auto verbose = parser.flag("-v").alias("--verbose").help("Verbose output");
    auto helpFlag = parser.flag("-h").alias("--help").help("Show help");

    if (!parser.parse()) {
        printUsage(argv[0]);
        return 1;
    }
    if (helpFlag.get()) {
        printUsage(argv[0]);
        return 0;
    }

    const auto &positional = parser.positional();
    std::string command = positional.size() > 0 ? positional[0] : "";

    if (command == "init") {
        const std::filesystem::path initPath = positional.size() > 1 ? positional[1] : std::filesystem::path(".");
        const InitResult initResult = initializeProject(initPath);
        if (!initResult.ok) {
            std::print(std::cerr, "Error: {}\n", initResult.message);
            return 1;
        }
        std::print("{}\n", initResult.message);
        std::print("Created:\n  {}\n  {}\n",
                   (initResult.projectDir / "Riko.toml").string(),
                   (initResult.projectDir / "src" / "main.rynt").string());
        std::print("Next: riko build {} --manifest-path {}\n",
                   initResult.targetName, (initResult.projectDir / "Riko.toml").string());
        return 0;
    }

    if (command != "build" && command != "check" && command != "run") {
        if (!command.empty()) {
            std::print(std::cerr, "Unknown command '{}'.\n", command);
        }
        printUsage(argv[0]);
        return 1;
    }

    std::string targetName = positional.size() > 1 ? positional[1] : targetOpt.value_or("");
    if (targetName.empty()) {
        std::print(std::cerr, "No target specified.\n");
        printUsage(argv[0]);
        return 1;
    }

    std::filesystem::path manifestPath = manifestPathOpt.value_or("./Riko.toml");
    if (!std::filesystem::exists(manifestPath)) {
        std::print(std::cerr, "Error: manifest '{}' not found.\n", manifestPath.string());
        return 1;
    }
    manifestPath = std::filesystem::absolute(manifestPath).lexically_normal();
    const std::filesystem::path manifestDir = manifestPath.parent_path();

    Manifest manifest;
    try {
        manifest = loadManifest(manifestPath);
    } catch (const std::exception &e) {
        std::print(std::cerr, "Error: {}\n", e.what());
        return 1;
    }

    auto targetIt = manifest.targets.find(targetName);
    if (targetIt == manifest.targets.end()) {
        std::print(std::cerr, "Error: target '{}' not found in manifest.\n", targetName);
        if (!manifest.targets.empty()) {
            std::string available;
            for (const auto &[name, unused] : manifest.targets) {
                if (!available.empty()) {
                    available += ", ";
                }
                available += name;
            }
            std::print(std::cerr, "Available targets: {}\n", available);
        }
        return 1;
    }
    const Target &target = targetIt->second;

    if (verbose.get()) {
        std::print(std::cerr, "[riko] target '{}': entry='{}', package_root='{}'\n",
                   target.name, target.entry, target.packageRoot);
    }

    CompileOptions options;
    options.strict = manifest.strict;
    options.verbose = verbose.get();

    CompileResult result = compileTarget(manifest, target, manifestDir, options);
    Ryntra::Compiler::ErrorHandler::getInstance().print();
    if (!result.ok) {
        return 1;
    }

    if (emitIR.get()) {
        std::cout << result.module->toString();
        return 0;
    }
    if (emitBytecode.get()) {
        Ryntra::VM::VirtualMachine vm;
        vm.load(result.bytecode, result.constantPool);
        vm.disassemble();
        return 0;
    }
    if (command == "check") {
        if (verbose.get()) {
            std::print(std::cerr, "[riko] check OK.\n");
        }
        return 0;
    }

    // build / run: execute the entry package's `main` in-process.
    try {
        Ryntra::VM::VirtualMachine vm;
        vm.load(result.bytecode, result.constantPool);
        vm.execute(result.entrySymbol);
    } catch (const Ryntra::Compiler::RuntimeErrorException &e) {
        Ryntra::Compiler::ErrorHandler &handler = Ryntra::Compiler::ErrorHandler::getInstance();
        handler.makeError(e.getDescription(), e.getRange());
        for (const auto &frame : e.getTrace()) {
            handler.makeHint("Call from '" + frame.callerName + "'", frame.callSite);
        }
        handler.print();
        return 1;
    } catch (const std::exception &e) {
        std::print(std::cerr, "Error: {}\n", e.what());
        return 1;
    }

    return 0;
}
